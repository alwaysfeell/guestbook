create table users (
    id       bigint generated by default as identity primary key,
    username varchar(64)  not null,
    password varchar(100) not null,
    role     varchar(16)  not null,
    constraint uk_users_username unique (username),
    constraint ck_users_role check (role in ('ADMIN', 'USER'))
);

create table books (
    id       bigint generated by default as identity primary key,
    title    varchar(255) not null,
    author   varchar(255) not null,
    pub_year integer      not null
);

create table comments (
    id         bigint generated by default as identity primary key,
    book_id    bigint                      not null,
    user_id    bigint                      not null,
    text       varchar(1000)               not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint fk_comments_book foreign key (book_id) references books (id) on delete cascade,
    constraint fk_comments_user foreign key (user_id) references users (id) on delete cascade
);

create index idx_comments_book on comments (book_id, created_at);
create index idx_comments_user on comments (user_id, created_at);
